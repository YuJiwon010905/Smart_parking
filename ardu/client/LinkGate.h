// ─────────────────────────────────────────────────────────────────────────
// 🔴 살아있음 불변식 — **실패 모드를 세지 않고 결과를 본다**
//   *"온라인이라면서 T초 동안 한 줄도 못 내보냈으면 끊는다."*
//
// 🔑 **왜 이 형태인가**: 실패 종류마다 카운터를 다는 방식은 **아는 실패만** 막는다.
//   `busy` 든 `ERROR` 든 침묵이든 **아직 이름이 없는 무엇이든** 여기에 걸린다.
// ⚠ 이 불변식이 없으면 *"`busy` 를 세지 않는다"* 는 규칙이 **조용한 영구 정지**를 만든다 —
//   `busy` 만 계속 오면 연속 실패 카운터가 영원히 3에 못 닿아 회복 경로가 사라진다.
//
// `T = 10000` : 서버 무프레임 판정(3.5초)과 3연속 실패 경로(약 3초)보다 **확실히 길어서**
//   평범한 문제는 그쪽이 먼저 잡고, 무한 정지보다는 **확실히 짧다.**
// ─────────────────────────────────────────────────────────────────────────
static const uint16_t TX_STALL_MS = 10000;
static uint32_t      lastTxOkAt   = 0;     // 마지막으로 **실제로 나간** 프레임의 시각
// 아래 셋은 **진단 전용이다. 제어에 쓰지 않는다** — 원인별로 따로 끊는 경로를 만들면
//   그게 다시 "아는 실패만 막는" 구조가 된다.
static uint8_t       stallBusy = 0, stallTimeout = 0, stallReject = 0;

// 프롬프트를 놓쳐 스트림을 강제 복구한 횟수.
// 🔴 **기대값은 0 이다. 서버의 `버린줄` 카운터와 크기 비교로 무엇을 판정하지 마라.**
//   실측 기전: 프롬프트를 놓치는 경우는 거의 전부 **ESP 가 명령 모드**다. 그러면 더미가
//   소켓이 아니라 **AT 해석기**로 들어가 **서버에는 줄이 도달조차 하지 않는다.**
//   ⚠ 즉 둘은 같은 사건을 두 번 보는 것이 아니라 **애초에 다른 사건**이다.
//   교차검증을 하려면 **갈래를 먼저 가른 뒤** 데이터 모드 갈래만 서버 카운터와 견줘라.
static uint16_t      promptResyncs = 0;

// ─────────────────────────────────────────────────────────────────────────
// 🔴 `SEND OK` 게이트 — **고정 지연 추측 대신 실제로 기다린다**
//   옛 방식은 "앞 전송이 끝났겠지" 하고 고정 지연 뒤 다음 `CIPSEND` 를 쐈다. 그 지연은
//   **우리가 쓰기를 끝낸 시각**부터 재는 것이지 **ESP 가 WiFi 로 다 보낸 시각**이 아니다 —
//   망이 느리면 ESP 는 아직 보내는 중이고 그때 쏘면 `busy` 로 거부된다.
//
// ⚠ **비블로킹이어야 한다.** 여기서 눌러 기다리면 하트비트(1Hz)와 하행(`+IPD`) 처리가
//   통째로 밀린다. 그래서 "기다린다" 가 아니라 **"아직이면 이번 주기를 건너뛴다"** 다.
// ⚠ `awaitingSendOk`·`sendOkT1Passed` 의 **선언은 파일 앞쪽에 있다** —
//   `feedRxChar()` 가 `SEND OK` 를 바이트 흐름에서 잡으려면 그보다 앞이어야 한다.
// ─────────────────────────────────────────────────────────────────────────
static uint32_t      sendOkWaitFrom  = 0;      // 그 기다림이 시작된 시각
//   ⚠ 없으면 T1~T2 구간의 **매 주기마다** `okto` 가 오른다 — 사건 수가 아니라 증상 수가 되어
//     monitor 계수와 정의가 어긋난다.

// 🔴 **상한이 필요한 이유**: `SEND OK` 가 **영영 안 올 수도 있다**(AT 판본이 안 주거나,
//   SoftwareSerial 이 반이중 + RX 64B 라 쓰는 동안 도착한 응답이 사라진다).
//   상한이 없으면 이 게이트가 **옛 방식보다 더 나쁜 정지**를 만든다.
// ⚠⚠ **그런데 상한은 공짜가 아니다 — ESP 리셋 탐지가 그만큼 늦어진다.**
//   ESP 가 죽으면 `SEND OK` 가 영영 안 오는데 그동안 우리는 **건너뛰기만 하고 아무것도 안 센다.**
//   즉 상한이 풀릴 때까지 **3연속 실패 판정이 시작되지도 못한다.**
//
// `2000` 의 근거 — **실측이다**(페이로드 쓰기 완료 → `SEND OK` 구간을 직접 쟀다):
//   표본 6,880 · Δ=0s **99.7%** · Δ=1s 0.3% · **Δ≥2s 0건**
//   🔑 말할 수 있는 것 : **2000ms 는 관측된 정상 분포를 자르지 않는다**
//   ⚠ 말할 수 **없는** 것 : 여유가 얼마인지 — 로그 해상도가 1초라 `Δ=1s` 의 실제 경과는
//     (0,2)초 어딘가다. 그래서 "안전하다" 가 아니라 **"실측과 모순 없다"** 까지만 주장한다.
//
// 🔑 **3000 이 아니라 2000 을 고른 이유 — 두 실수의 값이 비대칭이다:**
//   · 너무 일찍 자르면 → **옛 동작으로 되돌아갈 뿐**이고 `okto` 에 계상되어 **스스로 드러난다**
//   · 너무 늦게 풀면   → **ESP 가 죽었는데 그만큼 눈이 먼다**
//   → **비가역·비관측 쪽 실수를 피한다.**
// ★ 그리고 이 선택은 **자기교정된다**: `okto` 가 `[CNT]` 줄로 항상 나간다.
//   기대치보다 크게 나오면 2000 이 빡빡하다는 증거이므로 **그때 근거를 갖고 올린다.**
static const uint16_t SEND_OK_TIMEOUT_MS = 2000;
