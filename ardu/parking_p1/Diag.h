// ─────────────────────────────────────────────────────────────────────────
// RAM 여유 계측 — 버퍼 크기를 추정이 아니라 관측으로 정하기 위한 것
//
// 컴파일러가 알려 주는 정적 사용량은 **실행 중 스택이 얼마나 깊이 내려가는지 말하지 않는다.**
// ⚠ `-fstack-usage` 는 이 툴체인에서 **`.su` 파일이 비어 나온다** — 쓸 수 없다.
// 그래서 **가장 깊은 호출 지점에서 직접 잰다.** 힙을 안 쓰므로(`String`·`malloc` 없음)
// `__heap_start` 부터 현재 스택 포인터까지가 그대로 미사용 영역이다.
// ⚠ 이 값은 **"계측을 심은 지점에서 관측된 최저 여유"** 이지 이론적 최악값이 아니다.
// ─────────────────────────────────────────────────────────────────────────
extern uint8_t __heap_start;
static uint16_t ramLow = 0xFFFF;

static void ramProbe(void) {
  uint8_t here;
  uint16_t freeNow = (uint16_t)(&here - (uint8_t*)&__heap_start);
  if (freeNow < ramLow) ramLow = freeNow;
}

