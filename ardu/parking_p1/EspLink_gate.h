// 🔴🔴 **위치를 옮기지 마라.** `LinkGate.h` 의 정해진 자리에서 `#include` 된다.
//   헤더 순서가 바뀌면 선언 순서가 같이 바뀌어 **산출물이 달라진다.**
// ⚠ **`arduino/client/EspLink.h` 와 다른 파일이다.** 그쪽은 칩에 올라간 적이 없다 — 그것으로 굽지 마라.

// ─────────────────────────────────────────────────────────────────────────
// 🔴 SEND OK 3단 게이트 — **기다리는 동안 두들기지 않는다**
//
//   1단 (0 ~ T1)   조용히 기다린다
//   2단 (T1 ~ T2)  **계속 조용히 기다린다** ← 여기서 재전송하면 막힌 ESP 를 더 막는다
//   3단 (> T2)     복구로 간다
//
// ★ 이유를 묻지 않는다 — `busy` 든 침묵이든 **"`SEND OK` 가 왔는가" 하나만** 본다.
//   그래서 `busy` 전용 카운터를 두지 않는다.
//
// 🔴 `T2 = 8000` 은 **세 경계**가 정한 값이다(분포에서 뽑은 것이 아니다):
//   ① **6000ms 초과** — 서버의 무프레임 판정(3.5초)보다 길어야 정상 회복을 안 자른다
//   ② **`TX_STALL_MS`(10000) 미만** — 아니면 살아있음 불변식이 먼저 걸려 **3단이 영영 안 돈다**
//   ③ 관측된 회복을 안 자른다 — 실측 회복의 최대가 (6000, 8000)ms 구간에 있었다
//   ⚠ **대가**: ESP 가 진짜 죽었을 때 탐지가 `T2` 만큼 늦어진다. 불변식(10초)이 뒤를 받치므로
//     사라지지는 않고 늦어질 뿐이며, 그 늦어짐이 `T2 < TX_STALL_MS` 로 제한된다.
// ─────────────────────────────────────────────────────────────────────────
static const uint16_t SEND_OK_GIVEUP_MS = 8000;
static uint16_t      sendOkGiveups = 0;        // 3단 복구 발동 수(`stuck`) — **T2 의 자기교정 계기**
//   🔑 읽는 법 : `okto` 많고 `stuck` 적다   → 느린 전송이 2단에서 회복한다 → T2 적절
//               `stuck` 이 `okto` 에 가깝다 → 기다려도 안 온다 → **T2 를 낮춰야** 한다
//   ⚠ 기대치를 미리 박지 마라 — 옛 기대치와 견주다 데인 자리다(원장 §6.5-1).
static uint16_t      sendSkips      = 0;       // 진단: SEND OK 대기로 건너뛴 주기 수
static uint16_t      sendFails      = 0;       // 진단: SEND FAIL 수신 횟수

// ─────────────────────────────────────────────────────────────────────────
// 🔴 ESP IP 소실 탐지 — **진단 전용. 제어에 쓰지 않는다**
//
//   판별자 : **(`CIFSR` 응답이 `0.0.0.0`) OR (`CIFSR` 을 3회 물어도 쓸 IP 가 없었다)**
//
// ⚠ **부트 배너를 판별자로 쓰지 마라** — **매 기동에 뜬다.** 정상 부팅을 리셋으로 센다(오탐).
// ⚠ 그리고 `0.0.0.0` **단독으로도 부족하다** — 리셋이 심하면 `CIFSR` 응답 자체가 깨져
//   그 문자열이 안 나온다. 🔴 **놓치는 방향이 "제일 중요한 사건" 쪽이다.**
//   → 뒤쪽 가지(3회 소진)가 응답이 깨져도 성립하므로 그 구멍을 메운다.
//
// 🔑 `0.0.0.0` 이 뜨는 기전: ESP 가 제멋대로 리셋되면 우리는 아직 online 이라 믿고 있다가
//   사다리의 **CIFSR 단부터 재진입**하는데, 그때 ESP 가 아직 AP 에 못 붙어 주소가 없다.
//   **정상 부팅은 CWJAP 를 끝낸 뒤 CIFSR 로 오므로 절대 0 이 아니다.**
//
// 🔴 **걸쇠(latch)가 필요한 이유**: 한 번의 리셋에서 `0.0.0.0` 이 여러 번 오고 그 뒤 3회 소진까지
//   가면 **한 사건이 네 번 세진다.** 그러면 이 값은 "사건 수" 가 아니라 "증상 수" 가 되어
//   monitor 의 사건 계수와 **정의가 어긋난다.** → IP 를 잃은 순간 **한 번만** 세고,
//   실제로 IP 를 되찾을 때 푼다.
// ─────────────────────────────────────────────────────────────────────────
static uint16_t      espResets = 0;      // ESP 가 IP 를 잃은 **사건 수** (증상 수가 아니다)
static bool          ipLossLatched = false;

// 🔴 `CIFSR 3회 소진` 가지의 **오탐 방어**: ESP 가 바쁘면 `AT+CIFSR` 에도 `busy` 로 답한다 —
//   **IP 를 잃어서가 아니라 물어보지 못해서** 소진된다. 실측에서 `esprst` 절반이 이 오탐이었다.
//   ⚠ 오탐 방향이 한쪽이다 — **자해를 모듈 리셋으로** 옮긴다. 두 기전을 가르려는 계수기가
//     바로 그 자리에서 둘을 섞는다.
//   → **"물어봤는데 답에 IP 가 없었다"** 와 **"물어볼 수조차 없었다"** 를 가른다.
static bool          cifsrRefused = false;   // 이번 CIFSR 라운드에서 `busy` 로 거부된 적이 있다

// ⚠ **이름이 주장보다 세다.** 이 값은 `startSocketRecovery()` **진입 수**이고,
//   그 함수 자신이 판정을 **추정**이라고 밝힌다 — 재시도에 `ALREADY CONNECTED` 가 오면
//   **링크는 살아 있었던 것**이고 그대로 복귀한다. **"판단" 과 "실제" 는 다르다.**
static uint16_t      linkDrops = 0;      // 끊겼다고 **판단해** 복구에 들어간 횟수 — 실제 단절 여부는 별개

// ⚠⚠ **monitor 계수와 짝지을 때 — 이름이 비슷한 칸끼리 붙이지 마라**
//   | 내 칸 | monitor 의 짝 |
//   |---|---|
//   | `drop`   | **전체 사건 수**(모든 갈래 합) |
//   | `esprst` | **`리셋계열` + `혼합`** ← `리셋계열` 만 붙이면 어긋난다 |
//   🔑 `espResets` 는 **IP 소실**에서 세고 monitor 는 `busy` 표지가 같이 있는 사건을 `혼합` 으로
//   따로 뺀다. **둘 다 맞는 값이고 정의가 다를 뿐이다** — 모르고 보면 "계수기가 고장났다" 로 읽는다.
