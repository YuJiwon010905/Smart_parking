// 🔴🔴 **위치를 옮기지 마라.** `client.ino` 의 정해진 자리에서 `#include` 된다.
//   헤더 순서가 바뀌면 선언 순서가 같이 바뀌어 **산출물이 달라진다.**

// ─────────────────────────────────────────────────────────────────────────
// 🔴 자리 비트열의 **hex 인코딩** — 비트 순서가 우리 `mask` 와 **반대다**
//
//     `node.occMask` 안 : 슬롯 i = **비트 i**        (LSB 쪽이 슬롯 0)
//     전선 hex          : 슬롯 i = **비트 (n−1−i)**  (= 10진 문자열을 그대로 이진수로 읽은 값)
//
// ⚠ **뒤집지 않으면 길이도 체크섬도 통과하고 자리만 뒤집힌다.**
//   검산: 슬롯 {1,2,6,8,9} → mask 0x346 → 뒤집으면 0x18B → 문자열 "0110001011" 과 일치
// ⚠ **`0000…`·`1111…` 로 시험하지 마라** — 뒤집혀도 같아서 순서를 검증하지 못한다.
//   **비대칭 패턴만이 검증자다.**
// 🔑 hex 인 이유: 10진 1칸=1비트면 폭이 `n` 에 비례한다. hex 면 `n=10` 에서 60B → 39B 로 줄고
//   그만큼 배치에 ACK 이 더 들어간다.
//
// 🔴 **`n` 은 센서 수가 아니라 *모듈 수* 다** — 센서 + 액추에이터 합이다.
//   `S` 폭·hex 폭·뒤집기 축이 **전부 이 함수 하나를 따라간다.** 그래서 여기 하나로 모은다.
// ⚠ **센서 수를 인코더에 직접 쓰지 마라** — 값이 우연히 같은 구성에서는 맞고 액추에이터가
//   하나 늘면 조용히 틀린다. 길이도 체크섬도 통과하고 자리만 어긋나는 그 부류다.
// ─────────────────────────────────────────────────────────────────────────
static uint8_t moduleCount(void);   // ★ 표가 원천이다 — 정의는 `Module.h` 에 있다

// ─────────────────────────────────────────────────────────────────────────
// 🔴 등록(`D`) — 접속하면 자기가 무엇을 가졌는지 먼저 알린다
//
//   D,*,<drain>          ← **묶음의 맨 앞.** 자기 완결적이라 언제 와도 같은 뜻이다
//   D,<name>,<kind>      ← 이후 모듈들. 전부 같은 필드 수
//
// 🔑 **`*` 를 맨 앞에 둔 이유는 확장이다.** "마지막 줄"·"첫 줄" 규칙은 **파서가 몇 번째 줄인지
//   알아야 해서**, 모듈이 늘어 `D` 를 다시 보낼 때 *"이것도 첫 줄인가"* 가 애매해진다.
//
// 🔴 **`kind` 첫 글자의 뜻**: `O` = 하행 명령을 받는다 · `I` = 관측 전용.
//   **둘 다 비트열에는 들어간다**(출력 모듈도 상태를 보고한다 — 입력/출력 분할이 아니다).
//   ⚠ 실패 방향: 첫 글자가 `O` 가 아니면 **명령을 안 보낸다.** 모르는 글자도 금지 쪽으로 떨어진다 —
//     **모르는 장치에 명령을 보내는 것이 안 보내는 것보다 위험하다.**
//   ⚠ 그래도 **모르는 `kind` 를 거절하지는 않는다** — 거절하면 새 모듈 하나가 옛 서버에서
//     **노드 전체를 미등록으로** 만든다.
// ─────────────────────────────────────────────────────────────────────────

// 🔴 **배출률 선언값** — 한 주기에 배출할 수 있는 ACK 개수의 **보장 하한**이다.
//   ⚠ **관측 최대가 아니다.** 실측 `8` 은 `S` 가 짧고 rid 3자리일 때만 성립하는 조건부였고
//     보장은 그보다 작았다. 🔑 **조건부 실측을 보장으로 승격시키지 않는다.**
//   계산(최악값): S_worst ≈ 45B · ACK_worst ≈ 15B
//     D = (BATCH_CAP − S_worst − 1) ÷ (ACK_worst + 1) = (160 − 45 − 1) ÷ 16 = 7.1 → **7**
//   🔑 이 값이 **장치 쪽에 있는 이유**: 서버가 그 식을 들고 있으면 우리가 `BATCH_CAP` 을 바꿀 때
//     두 곳이 갈린다. **파생값은 원본을 가진 쪽이 계산한다.**
static const uint8_t DRAIN_DECL = 7;

// ─────────────────────────────────────────────────────────────────────────
// 등록 상태 — ⚠ **온라인 전이가 두 곳이라 반드시 함수로 모은다.** 한 곳만 고치면 어긋난다.
//
// 🔴 **첫 슬롯은 `S`, 둘째 슬롯부터 `D`**
//   왜 `D` 가 먼저가 아닌가 — **`D` 에는 devid 가 없다.** 서버의 소켓→노드 **승격**은 devid 를
//   가진 프레임으로 일어나는데 `D,*` 도 `D,<name>,<kind>` 도 그것을 안 싣는다.
//   → 🔴 **첫 슬롯에 `D` 를 보내면 승격 전 버퍼에서 등록 줄이 통째로 죽는다.**
//   🔑 그리고 `S` 는 원래 **반송파·생존 신호·슬롯 시작 통보** 셋을 겸한다 —
//      첫 프레임이어야 할 이유가 이미 있었다.
// ─────────────────────────────────────────────────────────────────────────
static bool     regPending  = false;   // 다음 송신 창에 `D` 를 보내야 한다
static bool     regAfterS   = false;   // 첫 `S` 가 나가면 그때 `D` 를 예약한다
static uint16_t regSends    = 0;       // 보낸 횟수(재전송 포함) — 진단용

// 새 소켓이 섰다. **바로 `D` 를 예약하지 않는다** — 승격이 먼저다.
static void markNeedsRegistration(void) { regPending = false; regAfterS = true; }

// 🔴 `Q` 를 받았다 — **이건 다르다. 바로 `D` 를 예약한다.**
//   `Q` 가 왔다는 것은 **서버가 이 소켓을 이미 노드로 승격했다**는 뜻이다(아니면 어디로 보낼지
//   모른다). **그래서 `S` 를 한 번 더 보낼 이유가 없다.**
//   ⚠ 두 경우에 같은 함수를 쓰면 `Q` 응답이 한 슬롯 늦어지고 서버의 3회 상한을 앞당긴다.
static void requestRegistrationNow(void) { regPending = true; regAfterS = false; }
