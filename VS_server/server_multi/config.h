//   `S_worst` 는 자리 수 `n` 에 따라 커진다 — n=10 → 60B → 배출 6 · n=15 → 75B → 배출 **5**.
//   그러면 유입 4 가 조용히 1건 초과가 된다.
// 🔑 **서버가 이 값을 다시 계산하지 않는다.** `BATCH_CAP`·`ACK_worst` 는 장치의 값이고
//   **파생값은 원본을 가진 쪽이 계산한다.** 사본을 두면 규칙이 두 곳에 생긴다.
//   → 최종형은 **장치가 등록(`D`)에서 자기 배출률을 선언하는 것**이다.
//   → 그때까지 서버는 **전제가 깨진 것만 감지한다** — 볼 수 있는 것은 `S` 의 길이뿐이고,
//     그것이 이 가정을 넘으면 배출 6 의 전제가 깨진 것이다.
static const int  DEV_S_WORST_ASSUMED_B = 60;   // n=10 기준 · arduino REQ-0206

// ---------------------------------------------------------------- 등록(§5)
// **상수가 아니라 유도값이다.** 접속 → 자기 송신 창 1슬롯 · `S`(승격) 1슬롯 · `D` 1슬롯 = 3슬롯.
