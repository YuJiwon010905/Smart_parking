static const uint16_t RID_SPACE = 1000;    // rid ∈ [0,999] — 최대 3자리
static const uint16_t RID_NONE  = 0xFFFF;  // "발행 못 했다" — RID_SPACE 밖이라 유효값과 안 겹친다
// 🔴 **폭보다 먼저 답해야 하는 것은 재사용 주기다.** 장치는 최근 서로 다른 `rid` 16개를 멱등
//   캐시에 들고, 그 안에서 값이 재등장하면 **명령을 적용하지 않고 옛 ACK 을 재전송한다.**
//   서버는 ACK 을 받으므로 타임아웃도 안 뜬다 — **실패가 성공처럼 보인다.**
// ⚠ `RID_SPACE` 를 내릴 때는 반드시 이 상수를 같이 봐라. **16 이하면 구조적으로 항상 충돌한다.**
static const int  DEV_RID_CACHE_N = 16;    // arduino CACHE_N (그쪽 소스 판독 · 실기 실측 아님)
// 격리 — 해제된 rid 를 얼마나 묵혔다 재사용하나. **리터럴 금지: 상수에서 유도한다.**
//   근거: 서버가 명령을 포기하는 것은 `ACK_MAX_TRIES` 번의 타임아웃을 다 쓴 뒤다. 그보다 늦게
//   오는 ACK 은 재전송 예산 전체보다 늦은 것이므로 없는 것으로 다룬다.
// ⚠ **이건 가정이지 관측이 아니다.** 그래서 `ack_unknown_rid` 를 요약에 낸다 —
