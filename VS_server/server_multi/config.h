static const int  DOWN_PROBE_N = 1;

// 🔴🔴 **자리 인수 유예 — `IP 가 다를 때만` 쓰인다. 그 종속을 빼고 읽으면 반드시 틀린다.**
//   *"정상 재접속 문턱"* 으로 읽으면 **`0초` 재접속을 막는 값**이 된다.
//   정상 재접속의 공백은 **최소 0초**다(실측) — 장치가 TCP 를 다시 세울 때 옛 소켓의 마지막
//   프레임 직후에 새 연결이 올 수 있다. **공백만으로 갈랐다면 우리 재접속을 여러 건 막았다.**
// 🔑 **1차 판별자는 시간이 아니라 IP 다.** `devid` 가 고유하지 않은 것이 뿌리이고, 그때 남는
//   유일한 구분자가 커널이 주는 주소다.
//     같은 IP → 같은 장치의 TCP 재접속 → **공백과 무관하게 교체 허용**
//     다른 IP → 두 대다 → 이 유예로 판정
//   하한: 정상 주기(1슬롯)보다 충분히 커야 한다
//   상한: 장치의 자체 재접속(약 8초)보다 작아야 한다 — 안 그러면 자리를 못 비켜 준다
// ⚠ 계약 줄에도 `(IP 다를 때만)` 을 붙여 찍는다. **값만 옮겨 적히는 것을 막으려는 것이다.**
static const int  TAKEOVER_GRACE_MS = 5 * DOWN_SLOT_MS;   // = 6000ms · 다른 IP 가 조용한 자리를 가져갈 때만

// ── ACK 마감 — 🔴 **값이 아니라 유도식이다**
// **유도**: ACK 은 장치의 **다음 송신 창**을 기다린다 → 한 슬롯. 그 창을 **한 번 놓친 경우까지
//   봐준다** → 한 슬롯 더. → `2 × DOWN_SLOT_MS`. 정상 왕복 ≈1230ms 대비 여유 ≈1170ms.
// 🔴 **`rtt_max` 를 쓰지 않는다.** 최대는 이상치를 포함하므로 거기 맞추면 **실패 감지가 그만큼
//   느려진다** — 이 마감이 하려는 일의 반대다.
// 🔑 **리터럴로 두지 않는 이유**: 슬롯 주기가 바뀌면 이 값이 따라 움직여야 한다. 박아 두면
//   `DOWN_SLOT_MS` 를 고친 사람이 이 상수를 잊는다.
static const int  ACK_TIMEOUT_MS = 2 * DOWN_SLOT_MS;   // §7.3 · 유도값(2400ms)

// ---------------------------------------------------------------- rid 폭·격리
//   정본: `docs/net/DESIGN-rid-width-and-quarantine.md`
// **왜 폭을 자르나**: 묶음 이득이 `rid` 자릿수에 걸려 있다.
//   3자리 → ACK 13B → N=3 이면 62B ✅ (대역 밖) · 4자리 → 14B → 65B 🔴 (이득 소멸)
// 단조 증가는 uint16 끝까지 자라므로 **설정을 안 바꿔도 지표가 저절로 움직인다.**
