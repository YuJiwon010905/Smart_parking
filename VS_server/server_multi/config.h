// `S` 가 안 오면 창이 영영 안 열린다 → 포기하고 쏜다.
// 🔴 **`OFFLINE_MS`(3500)보다 작아야 한다** — 그 뒤에 쏘면 서버가 이미 "장치 없음"으로 판단한
