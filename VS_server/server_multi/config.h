// 🔴 **재시작을 건너 단조성을 유지한다.** 서버가 1부터 다시 시작하면 장치 캐시에 남은 옛 rid 와
//   겹쳐 **명령이 삼켜지고 서버는 ACK 을 받아 성공으로 기록한다.**
// **블록 예약**: 한 번에 이만큼 앞을 예약해 디스크에 적고 그 안에서는 디스크를 안 만진다.
