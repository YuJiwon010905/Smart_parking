//   🔴 혼자 시험할 때는 아무 증상이 없고 **합치는 순간 서로 쫓아낸다** — 결함이 생기는 단계와
//   드러나는 단계가 멀다. 그래서 **로컬 서버가 그 자리에서 말한다.**
