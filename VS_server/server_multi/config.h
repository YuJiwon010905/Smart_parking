// ---------------------------------------------------------------- 전송 타임아웃
// 순서를 못 박는다:  한 프레임 ≈80ms  ≪  1000ms  <  `ACK_TIMEOUT_MS`  ≪  `OFFLINE_MS`
//   · `ACK_TIMEOUT_MS` 보다 짧아야 한다 — 길면 send() 에 갇힌 동안 재전송 타이머가 제 시각을
//     놓친다. **타임아웃이 타임아웃을 망친다.**
//   · `OFFLINE_MS` 보다 훨씬 짧아야 한다 — 길면 "장치가 죽었다"를 알아채야 할 시간에
//     서버가 send() 안에 멈춰 있는 셈이다.
// ⚠ 이 값은 `send_raw()` **한 번 전체**의 마감시각으로도 쓴다. `SO_SNDTIMEO` 는 `send()`
//   **한 호출**에만 걸려서, 상대가 조금씩만 빼가면 총 정지 시간이 얼마든지 길어진다.
//   그래서 둘 다 건다 — 소켓 옵션은 한 호출을, 마감시각은 한 프레임 전체를 막는다.
static const int SEND_TIMEOUT_MS = 1000;

// ---------------------------------------------------------------- 좀비 소켓 회수
// 장치가 FIN 없이 죽으면(전원 붕괴·ESP 행) 서버는 그 fd 를 영원히 들고 있는다. 재접속 자체는
// 안 막히므로(새 연결이 옛 소켓을 대체한다) 이건 결함 수리가 아니라 **위생**이다.
//
// ⚠ **두 장치는 중복이 아니다. 잡는 고장이 서로 다르다.**
//   · keepalive(OS) : 상대가 통째로 사라진 경우 — 전원 붕괴·망 분리. ACK 가 아예 안 온다.
//   · 유휴 마감(앱) : 상대 TCP 스택은 살아서 ACK 를 꼬박 보내는데 **앱이 조용한** 경우.
//                     🔴 keepalive 는 이걸 **원리적으로 못 잡는다** — 커널이 대신 응답한다.
//
// 하한 근거 — **"이 소켓 위에서 장치가 다시 말할 수 있는 최장 정체"보다 커야 한다.**
//   장치 사다리: CIPCLOSE 3회 ≈2.5초 · AT+RST 한 사이클 ≈14초 · CWJAP 대기 상한 30초
//   → 최악 약 44초. 60초는 그 위다.
// 상한 — 목적이 fd 회수이므로 길수록 뜻이 준다. 60초면 fd 하나가 최대 1분 낭비다.
// ⚠ **`OFFLINE_MS`(3.5초)에 바로 끊지 않는다.** 그건 "화면에 오프라인이라 쓴다"는 표시 판정이지
//   소켓 수명이 아니다. 거기서 끊으면 잠깐 늦은 프레임까지 죽인다.
//   순서:  3.5초(표시)  ≪  25초(keepalive)  <  60초(유휴 마감)
//
// ⚠⚠ **어느 시계로 재는가가 이 값보다 중요하다.** 유휴는 `ard_last_ms`(체크섬을 통과한 `S`
//   프레임 시각)로 잰다. `sess_last_line_ms`(수신한 모든 줄)로 재면 **AT 잡음이나 깨진 줄을
//   흘리는 장치가 영원히 살아남는다** — 줄은 계속 오니 유휴가 리셋되는데 `device_online()` 은
//   계속 false 다. **그게 정확히 회수해야 할 좀비다.**
static const int ARD_IDLE_CLOSE_MS = 60000;
// 탐지까지 10 + 5×3 = **25초**. 유휴 마감(60초)보다 먼저 걸리게 둔다 — OS 가 잡을 수 있는 고장은
// OS 가 먼저 잡는 편이 낫다(앱이 안 깨어나도 fd 가 돌아온다).
// `KEEPALIVE_IDLE_S` 는 `OFFLINE_MS` 보다 넉넉히 위라 **건강한 1Hz 링크에서는 한 번도 안 쏜다.**
static const int KEEPALIVE_IDLE_S  = 10;
static const int KEEPALIVE_INTVL_S = 5;
static const int KEEPALIVE_CNT     = 3;
// 복구시간 표본 상한 — 중앙값을 내려면 표본을 들고 있어야 하는데 상시가동에서 무한히 쌓을 수
// 없다. 넘으면 **더 담지 않고 그 사실을 요약에 적는다**(조용히 버리지 않는다).
static const size_t RECOV_SAMPLE_MAX = 10000;

// ---------------------------------------------------------------- 다중 노드
// 조원들이 각자 노드를 올린다. 옛 구조는 소켓을 하나만 들어 **두 번째 노드가 첫 번째를 끊었다.**
// **8 의 근거**: 조별과제 규모 4~6대 + 개발 예비 2대. 노드마다 1Hz 하트비트가 오므로 8대면
//   초당 8프레임이고, 그 이상은 단일 스레드 select 루프가 아니라 다른 구조를 논할 규모다.
// 🔑 **상한에 걸리면 새 연결을 거절한다(가장 오래된 것을 쫓아내지 않는다).**
//   살아서 도는 노드를 끊고 정체 모를 새 소켓을 들이는 것은 **확실한 것을 버리고 불확실한 것을
//   얻는 거래**다. 같은 `devid` 의 재접속은 자리를 물려받으므로 거절이 재부팅을 막지도 않는다.
static const size_t MAX_ARD_NODES = 8;

// **id 를 아직 모르는 소켓**의 상한과 마감. 첫 프레임을 받아야 `devid` 를 아는데 소켓은 그 전에
// 이미 존재한다. 그 사이의 소켓을 무한히 받아 주면 그것이 곧 자원 고갈이다.
// **근거**: `OFFLINE_MS`(3.5초) 무프레임이면 "말하지 않는 장치"다. 붙자마자 말을 안 하는 소켓은
//   **명세 자신의 기준으로 이미 죽은 것**이다. 접속 직후 AT 잡음으로 첫 줄이 깨질 수 있어 2배를
//   준다 = 7초. 1Hz 이므로 그 안에 **유효 프레임 기회가 7번** 있다.
// ⚠ **이 시계는 부팅이 아니라 `accept` 에서 시작한다.** 장치는 WiFi 결합·IP 확보를 **끝낸 뒤에야**
//   TCP 를 연다 — 부팅 12초는 **소켓이 존재하지도 않는 구간**이라 이 마감이 볼 수 없다.
//   (실측: accept→devid 확정 최대 1.0초 · 7초 초과 0건. 프레임 없이 마감된 소켓이 다시 말한 것은
//    중앙 404초 뒤 — **7초와 12초 사이에는 아무것도 없다.**)
// 🔴 **줄이지 마라.** 1~2초까지 낮추면 정상 세션을 끊기 시작하고, 끊긴 장치는 **0.90초 주기
//   무백오프**로 즉시 재접속한다 → `수락 → 마감 → 재접속` 사이클을 **서버가 스스로 만들어 낸다.**
static const int UNKNOWN_TIMEOUT_MS = OFFLINE_MS * 2;
static const size_t MAX_UNKNOWN_SOCKS = MAX_ARD_NODES;   // id 없는 소켓이 노드 예산을 넘지 못한다

