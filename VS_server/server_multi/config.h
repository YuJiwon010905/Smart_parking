//   장치 `loop()` 가 자주 비우면 더 흘릴 수 있지만 **그건 타이밍 종속이지 보장이 아니다.**
// ⚠ 늘리려면 **장치 쪽 링이 먼저 커져야 한다.** 서버에서만 올리면 거짓 보장이 된다.
