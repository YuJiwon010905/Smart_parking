static const int  DOWN_DMAX_MS       = 2 * DOWN_SLOT_MS;
// 한 줄 상한. 장치 `RX_CAP=96` 안에 `"+IPD,<n>:"` 접두(8~9B)가 **포함된다.**
// **배치 전체가 아니라 줄 하나의 제약이다.**
static const int  DOWN_LINE_MAX_B    = 87;

// 🔴 **한 창에 밀어 넣는 바이트 상한.** 제약은 바이트가 아니라 **장치 UART 를 몇 ms 붙잡는가** 다.
// ```
//   장치 송신 종료(이론 최악) = slotStart + due 400 + txTime 468 = slotStart + 868
//   다음 장치 송신            = slotStart + 1200      → 내가 쓸 시간 332ms − d1(망 지연)
//   192B = 192 ÷ 960 B/s + 접두 9B = 209ms  ✅        320B = 342ms  🔴 이미 넘는다
// ```
// ⚠ **종속 셋. 하나라도 바뀌면 다시 계산한다:** ① 960 B/s(9600 baud) ② 장치 `txTime_max`
//   ③ **망 왕복 `d1+d2` — 미측정**(내 요약 `왕복 최대 Nms` 가 그 값을 낸다).
// 🔑 **이 값은 "회선의 한계"가 아니라 "이론 최악을 덮는 값"이다.** 실측 여유는 1152ms 라
//   192B 는 그 18% — 약 20배 보수적이다. **올릴 근거가 생기는 조건 셋을 미리 적어 둔다:**
//   ① `[SLOT] due=` 분포에 400 근처가 없다 ② `resync` 계수가 0 에 가깝다 ③ `왕복 최대` 실기값.
//   **셋이 다 나오면 재계산한다. 그 전에는 이 값으로 간다.**
// → 재빌드 없이 갈아끼우려면 `--down-cap=<B>`.
static int        DOWN_BATCH_CAP_B   = 192;
// 큐 깊이는 **독립 상수가 아니라 유도값이다** — "마감 안에 나갈 수 있는 양".
//   `cap` 이 바뀌면 깊이가 저절로 따라온다. 두 값이 따로 놀면 마감을 넘긴 항목이 큐에 남는데
//   아무도 그것을 설명하지 못한다.
static const int  DOWNQ_WAIT_CAP_MS  = 4 * DOWN_SLOT_MS;   // 4.8초 — 큐 대기 마감(임시)
// 🔴 착지 위상을 **의도적으로 겨냥하는 시험**을 위한 옛 거동(즉시 송신). 하행을 원하는 순간에
//   쏠 수단이 없으면 "착지 타이밍" 물음을 영영 못 가른다. **기본값은 off.**
static bool       DOWN_IMMEDIATE     = false;

// 🔴 **건수 상한 — 바이트와 다른 축이다.** 바이트만으로는 못 막는다: 명령이 작을수록 헐거워진다
//   (9B 명령이면 192B 가 21건을 통과시킨다). **회선은 바이트를 나르지만 장치는 건당 ACK 하나를 만든다.**
// **유도**: 유입 N · 배출 D. 한 슬롯을 놓치면 적체 2N → 2N−D → 3N−2D.
//   2슬롯에 회복하려면 `3N − 2D ≤ 0` → **N ≤ 2D/3** → D=6 이면 **4**.
// 🔴 **유입 = 배출이면 한 번만 밀려도 영구히 못 따라잡는다**(ρ=1). 여유가 필수다.
