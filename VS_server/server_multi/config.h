// ⚠ 반대로 "쓴 뒤에 적는" 방식이면 크래시 때 **가장 최근에 쓴 값들**을 재발행해
//   장치 캐시와 겹칠 확률이 가장 높은 구간을 정확히 다시 밟는다.
